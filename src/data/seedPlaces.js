/**
 * Normalizes seed places with dynamic distance calculated from city center
 */
export function getSeedPlaces(cityName, categoryId, centerLat, centerLon, radiusKm = 5) {
  if (!cityName) return [];

  const key = cityName.toLowerCase().replace(/[^a-z]/g, '');
  const cityKey = key.includes('pune') ? 'pune'
    : (key.includes('mumbai') || key.includes('bombay')) ? 'mumbai'
    : (key.includes('delhi')) ? 'delhi'
    : (key.includes('bengaluru') || key.includes('bangalore')) ? 'bengaluru'
    : null;

  if (!cityKey || !POPULAR_CITIES_SEEDS[cityKey]) {
    return [];
  }

  const allCityPlaces = POPULAR_CITIES_SEEDS[cityKey];
  const matching = categoryId
    ? allCityPlaces.filter(p => p.category === categoryId)
    : allCityPlaces;

  return matching.map(p => {
    const dist = (centerLat != null && centerLon != null)
      ? calculateDistance(centerLat, centerLon, p.lat, p.lon)
      : p.distance;

    return {
      ...p,
      distance: dist,
      formattedDistance: formatDistance(dist)
    };
  }).filter(p => (p.distance == null || p.distance <= radiusKm * 1.5));
}
